export const SSR_ANCHOR_MS = Date.UTC(2026, 10, 23, 12, 0, 0);

function daysFromAnchor(anchorMs: number, offsetDays: number): string {
  const d = new Date(anchorMs + offsetDays * 86_400_000);
  return d.toISOString().slice(0, 10);
}

function hoursBeforeAnchor(anchorMs: number, hours: number): string {
  return new Date(anchorMs - hours * 3_600_000).toISOString();
}

